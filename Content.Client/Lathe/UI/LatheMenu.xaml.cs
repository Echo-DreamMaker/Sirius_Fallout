    public LatheMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _spriteSystem = _entityManager.System<SpriteSystem>();
        _lathe = _entityManager.System<LatheSystem>();
        _materialStorage = _entityManager.System<MaterialStorageSystem>();
        _miningPoints = _entityManager.System<MiningPointsSystem>(); // DeltaV

        SearchBar.OnTextChanged += _ =>
        {
            PopulateRecipes();
        };
        BlueprintSearchBar.OnTextChanged += _ =>
        {
            PopulateRecipes();
        };
        AmountLineEdit.OnTextChanged += _ =>
        {
            PopulateRecipes();
        };

        FilterOption.OnItemSelected += OnItemSelected;

        ServerListButton.OnPressed += a => OnServerListButtonPressed?.Invoke(a);
    }

    public void SetEntity(EntityUid uid)
    {
        Entity = uid;

        if (_entityManager.TryGetComponent<LatheComponent>(Entity, out var latheComponent))
        {
            if (!latheComponent.DynamicRecipes.Any())
            {
                ServerListButton.Visible = false;
            }
        }

        // Begin DeltaV Additions: Mining points UI
        MiningPointsContainer.Visible = _entityManager.TryGetComponent<MiningPointsComponent>(Entity, out var points);
        MiningPointsClaimButton.OnPressed += _ => OnClaimMiningPoints?.Invoke();
        if (points != null)
            UpdateMiningPoints(points.Points);
        // End DeltaV Additions

        MaterialsList.SetOwner(Entity);
    }

    protected override void Opened()
    {
        base.Opened();

        if (_entityManager.TryGetComponent<LatheComponent>(Entity, out var latheComp))
        {
            AmountLineEdit.SetText(latheComp.DefaultProductionAmount.ToString());
        }
    }

    /// <summary>
    /// DeltaV: Updates the UI elements for mining points.
    /// </summary>
    private void UpdateMiningPoints(uint points)
    {
        MiningPointsClaimButton.Disabled = points == 0 ||
            _player.LocalSession?.AttachedEntity is not {} player ||
            _miningPoints.TryFindIdCard(player) == null;
        if (points == _lastMiningPoints)
            return;

        _lastMiningPoints = points;
        MiningPointsLabel.Text = Loc.GetString("lathe-menu-mining-points", ("points", points));
    }

    /// <summary>
    /// DeltaV: Update mining points UI whenever it changes.
    /// </summary>
    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_entityManager.TryGetComponent<MiningPointsComponent>(Entity, out var points))
            UpdateMiningPoints(points.Points);
    }

    /// <summary>
    /// Populates the list of all the recipes
    /// </summary>
    public void PopulateRecipes()
    {
        var itemRecipesToShow = new List<LatheRecipePrototype>();
        var blueprintRecipesToShow = new List<LatheRecipePrototype>();

        var itemSearch = SearchBar.Text.Trim().ToLowerInvariant();
        var blueprintSearch = BlueprintSearchBar.Text.Trim().ToLowerInvariant();

        foreach (var recipe in Recipes)
        {
            if (!_prototypeManager.TryIndex(recipe, out var proto))
                continue;

            if (CurrentCategory != null && proto.Category != CurrentCategory)
                continue;

            var recipeName = _lathe.GetRecipeName(proto).ToLowerInvariant();
            var isBlueprint = IsBlueprintRecipe(proto);

            if (isBlueprint)
            {
                if (blueprintSearch.Length == 0 || recipeName.Contains(blueprintSearch))
                    blueprintRecipesToShow.Add(proto);
            }
            else
            {
                if (itemSearch.Length == 0 || recipeName.Contains(itemSearch))
                    itemRecipesToShow.Add(proto);
            }
        }

        if (!int.TryParse(AmountLineEdit.Text, out var quantity) || quantity <= 0)
            quantity = 1;

        var sortedItemRecipesToShow = itemRecipesToShow.OrderBy(_lathe.GetRecipeName);
        var sortedBlueprintRecipesToShow = blueprintRecipesToShow.OrderBy(_lathe.GetRecipeName);

        RecipeList.Children.Clear();
        BlueprintRecipeList.Children.Clear();
        _entityManager.TryGetComponent(Entity, out LatheComponent? lathe);
        var materialUseMultiplier = lathe?.MaterialUseMultiplier ?? 1f;

        foreach (var prototype in sortedItemRecipesToShow)
        {
            // #Misfits Fix: Use server-provided material amounts when available so that
            // materials physically stored in the workbench storage container (not just
            // the material pool) are counted, enabling the button correctly.
            // #Sirius Add: include server-provided whole-item counts for item costs.
            var canProduce = ServerAvailableMaterials != null
                ? _lathe.CanProduce(Entity, prototype, quantity, ServerAvailableMaterials, ServerAvailableItems ?? new Dictionary<EntProtoId, int>(), materialUseMultiplier, component: lathe)
                : _lathe.CanProduce(Entity, prototype, quantity, materialUseMultiplier, component: lathe);

            var control = new RecipeControl(_lathe, prototype, () => GenerateTooltipText(prototype), canProduce, GetRecipeDisplayControl(prototype));
            control.OnButtonPressed += s =>
            {
                if (!int.TryParse(AmountLineEdit.Text, out var amount) || amount <= 0)
                    amount = 1;
                RecipeQueueAction?.Invoke(s, amount);
            };
            RecipeList.AddChild(control);
        }

        foreach (var prototype in sortedBlueprintRecipesToShow)
        {
            // #Misfits Fix: Same server-material-amount check for blueprint recipes.
            // #Sirius Add: include server-provided whole-item counts for item costs.
            var canProduce = ServerAvailableMaterials != null
                ? _lathe.CanProduce(Entity, prototype, quantity, ServerAvailableMaterials, ServerAvailableItems ?? new Dictionary<EntProtoId, int>(), materialUseMultiplier, component: lathe)
                : _lathe.CanProduce(Entity, prototype, quantity, materialUseMultiplier, component: lathe);

            var control = new RecipeControl(_lathe, prototype, () => GenerateTooltipText(prototype), canProduce, GetRecipeDisplayControl(prototype));
            control.OnButtonPressed += s =>
            {
                if (!int.TryParse(AmountLineEdit.Text, out var amount) || amount <= 0)
                    amount = 1;
                RecipeQueueAction?.Invoke(s, amount);
            };
            BlueprintRecipeList.AddChild(control);
        }

        // #Misfits Change Add: Refresh Section 2 whenever Section 1 is rebuilt
        PopulateBuildableRecipes();
    }

    /// <summary>
    /// #Misfits Change Add: Populates Section 2 — "Craftable Now".
    /// Shows only recipes the player currently has enough materials in the lathe to produce.
    /// Respects the active search text, category filter, and amount quantity.
    /// </summary>
    public void PopulateBuildableRecipes()
    {
        if (!int.TryParse(AmountLineEdit.Text, out var quantity) || quantity <= 0)
            quantity = 1;

        BuildableRecipeList.Children.Clear();
        _entityManager.TryGetComponent(Entity, out LatheComponent? lathe);
        var materialUseMultiplier = lathe?.MaterialUseMultiplier ?? 1f;

        var buildable = new List<LatheRecipePrototype>();
        var itemSearch = SearchBar.Text.Trim().ToLowerInvariant();
        var blueprintSearch = BlueprintSearchBar.Text.Trim().ToLowerInvariant();

        foreach (var recipeId in Recipes)
        {
            if (!_prototypeManager.TryIndex(recipeId, out var proto))
                continue;

            // Respect category filter
            if (CurrentCategory != null && proto.Category != CurrentCategory)
                continue;

            var recipeName = _lathe.GetRecipeName(recipeId).ToLowerInvariant();
            if (IsBlueprintRecipe(proto))
            {
                if (blueprintSearch.Length != 0 && !recipeName.Contains(blueprintSearch))
                    continue;
            }
            else
            {
                if (itemSearch.Length != 0 && !recipeName.Contains(itemSearch))
                    continue;
            }

            // Only include recipes the player can currently build
            // #Misfits Fix: Use server-provided material amounts when available.
            // #Sirius Add: include server-provided whole-item counts for item costs.
            var canBuild = ServerAvailableMaterials != null
                ? _lathe.CanProduce(Entity, proto, quantity, ServerAvailableMaterials, ServerAvailableItems ?? new Dictionary<EntProtoId, int>(), materialUseMultiplier, component: lathe)
                : _lathe.CanProduce(Entity, proto, quantity, materialUseMultiplier, component: lathe);
            if (canBuild)
                buildable.Add(proto);
        }

        foreach (var prototype in buildable.OrderBy(_lathe.GetRecipeName))
        {
            // Buildable controls are always enabled (canProduce = true)
            var control = new RecipeControl(_lathe, prototype, () => GenerateTooltipText(prototype), true, GetRecipeDisplayControl(prototype));
            control.OnButtonPressed += s =>
            {
                if (!int.TryParse(AmountLineEdit.Text, out var amount) || amount <= 0)
                    amount = 1;
                RecipeQueueAction?.Invoke(s, amount);
            };
            BuildableRecipeList.AddChild(control);
        }
    }

    private bool IsBlueprintRecipe(LatheRecipePrototype recipe)
    {
        // #Misfits Fix: Previously this checked whether the RESULT entity had STBlueprintComponent,
        // which classified "print a blueprint for Paper" recipes into the Blueprints tab.  That was
        // wrong — those print-recipes should not exist / should not be staticRecipes on any bench.
        // Instead, we use the explicit RequiresBlueprint flag: recipes in Section B (unlocked only
        // when the matching blueprint is placed in the workbench storage) set this to true and are
        // shown in the Blueprints sub-section with the item's actual material cost as the tooltip.
        return recipe.RequiresBlueprint;
    }

    private string GenerateTooltipText(LatheRecipePrototype prototype)
    {
        StringBuilder sb = new();
        _entityManager.TryGetComponent(Entity, out LatheComponent? lathe);
        var multiplier = lathe?.MaterialUseMultiplier ?? 1f;

        foreach (var (id, amount) in prototype.Materials)
        {
            if (!_prototypeManager.TryIndex(id, out var proto))
                continue;

            var adjustedAmount = SharedLatheSystem.AdjustMaterial(amount, prototype.ApplyMaterialDiscount, multiplier);

            // #Misfits Fix: Use server-provided material amounts if available so that
            // physical storage items (not yet composition-synced on client) are reflected.
            var availableAmount = ServerAvailableMaterials != null
                ? ServerAvailableMaterials.GetValueOrDefault(id, 0)
                : _materialStorage.GetAvailableMaterialAmount(Entity, id);
            var missingAmount = Math.Max(0, adjustedAmount - availableAmount);

            var name = Loc.GetString(proto.Name);
            var unit = Loc.GetString(proto.Unit);
            var sheetVolume = Math.Max(1, _materialStorage.GetSheetVolume(proto));
            var adjustedSheets = (float) adjustedAmount / sheetVolume;
            var missingSheets = (float) missingAmount / sheetVolume;

            string tooltipText;
            // #Misfits Fix: Tooltip costs should match sheet-backed material displays elsewhere
            // in the lathe UI, rather than exposing raw internal stack volume values.
            if (missingAmount > 0)
            {
                tooltipText = Loc.GetString("lathe-menu-material-amount-missing",
                    ("amount", adjustedSheets),
                    ("missingAmount", missingSheets),
                    ("unit", unit),
                    ("material", name));
            }
            else
            {
                tooltipText = Loc.GetString("lathe-menu-tooltip-display",
                    ("amount", Loc.GetString("lathe-menu-material-amount", ("amount", adjustedSheets), ("unit", unit))),
                    ("material", name));
            }

            sb.AppendLine(tooltipText);
        }

        // #Sirius Add: show whole-item costs (armor, dynamite, chips, wires, batteries) too.
        foreach (var (id, amount) in prototype.ItemCosts)
        {
            if (!_prototypeManager.TryIndex(id, out var itemProto))
                continue;

            var available = ServerAvailableItems?.GetValueOrDefault(id, 0) ?? 0;
            var missing = Math.Max(0, amount - available);
            var tooltipText = missing > 0
                ? Loc.GetString("lathe-menu-sirius-item-amount-missing", ("amount", amount), ("item", itemProto.Name), ("missing", missing))
                : Loc.GetString("lathe-menu-sirius-item-amount", ("amount", amount), ("item", itemProto.Name));

            sb.AppendLine(tooltipText);
        }

        // #Sirius Add: alternative item costs are shown as "one of these".
        foreach (var option in prototype.AnyOfItemCosts)
        {
            var parts = new List<string>();
            foreach (var (id, amount) in option)
            {
                if (!_prototypeManager.TryIndex(id, out var itemProto))
                    continue;

                var available = ServerAvailableItems?.GetValueOrDefault(id, 0) ?? 0;
                var missing = Math.Max(0, amount - available);
                parts.Add(missing > 0
                    ? Loc.GetString("lathe-menu-sirius-item-amount-missing", ("amount", amount), ("item", itemProto.Name), ("missing", missing))
                    : Loc.GetString("lathe-menu-sirius-item-amount", ("amount", amount), ("item", itemProto.Name)));
            }

            if (parts.Count > 0)
                sb.AppendLine(Loc.GetString("lathe-menu-sirius-one-of", ("costs", string.Join(" / ", parts))));
        }

        var desc = _lathe.GetRecipeDescription(prototype);
        if (!string.IsNullOrWhiteSpace(desc))
            sb.AppendLine(Loc.GetString("lathe-menu-description-display", ("description", desc)));

        // Remove last newline
        if (sb.Length > 0)
            sb.Remove(sb.Length - 1, 1);

        return sb.ToString();
    }


    public void UpdateCategories()
    {
        var currentCategories = new List<ProtoId<LatheCategoryPrototype>>();
        foreach (var recipeId in Recipes)
        {
            if (!_prototypeManager.TryIndex(recipeId, out LatheRecipePrototype? recipe))
                continue;

            if (recipe.Category == null)
                continue;

            if (currentCategories.Contains(recipe.Category.Value))
                continue;

            currentCategories.Add(recipe.Category.Value);
        }

        if (Categories != null && (Categories.Count == currentCategories.Count || !Categories.All(currentCategories.Contains)))
            return;

        Categories = currentCategories;
        var sortedCategories = currentCategories
            .Where(p => _prototypeManager.TryIndex(p, out LatheCategoryPrototype? _))
            .Select(p => _prototypeManager.Index(p))
            .OrderBy(p => Loc.GetString(p.Name))
            .ToList();

        FilterOption.Clear();
        FilterOption.AddItem(Loc.GetString("lathe-menu-category-all"), -1);
        foreach (var category in sortedCategories)
        {
            FilterOption.AddItem(Loc.GetString(category.Name), Categories.IndexOf(category.ID));
        }

        FilterOption.SelectId(-1);
    }

    /// <summary>
    /// Populates the build queue list with all queued items
    /// </summary>
    /// <param name="queue"></param>
    public void PopulateQueueList(List<LatheRecipePrototype> queue)
    {
        QueueList.DisposeAllChildren();

        QueueList.DisposeAllChildren();

        var idx = 1;
        foreach (var recipe in queue)
        {
            var queuedRecipeBox = new BoxContainer();
            queuedRecipeBox.Orientation = BoxContainer.LayoutOrientation.Horizontal;

            queuedRecipeBox.AddChild(GetRecipeDisplayControl(recipe));

            var queuedRecipeLabel = new Label();
            queuedRecipeLabel.Text = $"{idx}. {_lathe.GetRecipeName(recipe)}";
            queuedRecipeBox.AddChild(queuedRecipeLabel);
            QueueList.AddChild(queuedRecipeBox);
            idx++;
        }
    }

    public void SetQueueInfo(LatheRecipePrototype? recipe)
    {
        FabricatingContainer.Visible = recipe != null;
        if (recipe == null)
            return;

        FabricatingDisplayContainer.Children.Clear();
        FabricatingDisplayContainer.AddChild(GetRecipeDisplayControl(recipe));

        NameLabel.Text = _lathe.GetRecipeName(recipe);
    }

    public Control GetRecipeDisplayControl(LatheRecipePrototype recipe)
    {
        if (recipe.Icon != null)
        {
            var textRect = new TextureRect();
            textRect.Texture = _spriteSystem.Frame0(recipe.Icon);
            return textRect;
        }

        if (recipe.Result is { } result)
        {
            // #Misfits Fix - Some blueprint recipes have historically pointed at abstract or bad
            // result prototypes. EntityPrototypeView spawns the prototype for preview, so guard the
            // lookup here and fall back to an empty control instead of crashing the whole lathe UI.
            if (!_prototypeManager.TryIndex<EntityPrototype>(result, out var entityProto) || entityProto.Abstract)
                return new Control();

            var entProtoView = new EntityPrototypeView();
            entProtoView.SetPrototype(result);
            return entProtoView;
        }

        return new Control();
    }

    private void OnItemSelected(OptionButton.ItemSelectedEventArgs obj)
    {
        FilterOption.SelectId(obj.Id);
        if (obj.Id == -1)
        {
            CurrentCategory = null;
        }
        else
        {
            CurrentCategory = Categories?[obj.Id];
        }
        PopulateRecipes();
    }
