namespace Content.Client._Sirius.WeaponAssemblyStation;

[GenerateTypedNameReferences]
public sealed partial class WeaponAssemblyStationWindow : DefaultWindow
{
    private const float PartSize = 64f;
    private const float MainSize = 96f;
    private const float MagSize = 48f;
    private const float PartGap = 8f;
    private const float RowOffsetY = 8f;

    // #Misfits Add - the lower row of working slots sits a slot height plus a
    // 10% gap below the upper one.
    private const float RowOffsetY2 = RowOffsetY + PartSize + (PartSize * 0.1f);

    private const float PartPanelWidth = 120f;
    private const float MainPanelWidth = 150f;
    private const float PanelGap = 4f;
    private const float ContainerWidth = 450f;

    private static readonly string[] PartSlotIds =
    {
        WeaponAssemblyStationComponent.Part1SlotId,
        WeaponAssemblyStationComponent.Part2SlotId,
        WeaponAssemblyStationComponent.Part3SlotId,
        WeaponAssemblyStationComponent.Part4SlotId,
    };

    private readonly SlotButton[] _partSlots = new SlotButton[4];
    private readonly ItemStatusPanel[] _partItemStatus = new ItemStatusPanel[4];
    private readonly SlotButton _mainSlot;
    private readonly SlotButton _magSlot;

    // #Misfits Add - show the held/placed weapon's status panel next to the main slot.
    private readonly ItemStatusPanel _mainItemStatus;

    // #Misfits Add - repair panel: the body/frame button plus one per working slot.
    private readonly Button[] _repairButtons = new Button[5];

    public event Action<WeaponAssemblyUiButton>? OnButtonPressed;

    /// <summary>
    /// Raised when one of the station's item slots is clicked, with the container id of that slot.
    /// </summary>
    public event Action<string>? OnSlotPressed;

    public WeaponAssemblyStationWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("misfits-weapon-station-title");
        HeaderLabel.Text = Loc.GetString("misfits-weapon-station-title");
        StationCloseButton.Text = Loc.GetString("misfits-weapon-station-close");

        BoltButton.Text = Loc.GetString("misfits-weapon-station-bolt");
        DisassembleButton.Text = Loc.GetString("misfits-weapon-station-disassemble");
        AssembleButton.Text = Loc.GetString("misfits-weapon-station-assemble");

        BoltButton.OnPressed += _ => OnButtonPressed?.Invoke(WeaponAssemblyUiButton.Bolt);
        DisassembleButton.OnPressed += _ => OnButtonPressed?.Invoke(WeaponAssemblyUiButton.Disassemble);
        AssembleButton.OnPressed += _ => OnButtonPressed?.Invoke(WeaponAssemblyUiButton.Assemble);
        StationCloseButton.OnPressed += _ => OnButtonPressed?.Invoke(WeaponAssemblyUiButton.Close);

        // #Misfits Add - the repair buttons mirror WeaponAssemblyUiButton's own
        // repair order, so the index doubles as the operation the server runs.
        RepairLabel.Text = Loc.GetString("misfits-weapon-station-repair-label");
        _repairButtons[0] = RepairBodyButton;
        _repairButtons[1] = RepairBarrelButton;
        _repairButtons[2] = RepairBoltButton;
        _repairButtons[3] = RepairGripButton;
        _repairButtons[4] = RepairStockButton;

        var partRepairLabels = new[]
        {
            "misfits-weapon-station-repair-barrel",
            "misfits-weapon-station-repair-bolt",
            "misfits-weapon-station-repair-grip",
            "misfits-weapon-station-repair-stock",
        };

        for (var i = 0; i < _repairButtons.Length; i++)
        {
            if (i > 0)
                _repairButtons[i].Text = Loc.GetString(partRepairLabels[i - 1]);

            var operation = i;
            _repairButtons[i].OnPressed += _ => OnButtonPressed?.Invoke(
                (WeaponAssemblyUiButton) ((int) WeaponAssemblyUiButton.RepairBody + operation));
        }

        // #Misfits Change - slot 1 and 4 share the upper row, slot 2 and 3 the
        // lower one (shifted down by a 10% gap). Slot 1/2 use a right side panel
        // placed to their left, slot 3/4 a left side panel placed to their right.
        var rowWidth = 2 * PartSize + PartGap;
        var rowStartX = (ContainerWidth - rowWidth) / 2f;

        var slot1 = MakeSlot(PartSize, PartSlotIds[0]);
        SlotContainer.AddChild(slot1);
        LayoutContainer.SetPosition(slot1, new Vector2(rowStartX, RowOffsetY));
        _partSlots[0] = slot1;
        AddPartStatusPanel(slot1, 0, HandUILocation.Right, PartSize);

        var slot4 = MakeSlot(PartSize, PartSlotIds[3]);
        SlotContainer.AddChild(slot4);
        LayoutContainer.SetPosition(slot4, new Vector2(rowStartX + PartSize + PartGap, RowOffsetY));
        _partSlots[3] = slot4;
        AddPartStatusPanel(slot4, 3, HandUILocation.Left, PartSize);

        var slot2 = MakeSlot(PartSize, PartSlotIds[1]);
        SlotContainer.AddChild(slot2);
        LayoutContainer.SetPosition(slot2, new Vector2(rowStartX, RowOffsetY2));
        _partSlots[1] = slot2;
        AddPartStatusPanel(slot2, 1, HandUILocation.Right, PartSize);

        var slot3 = MakeSlot(PartSize, PartSlotIds[2]);
        SlotContainer.AddChild(slot3);
        LayoutContainer.SetPosition(slot3, new Vector2(rowStartX + PartSize + PartGap, RowOffsetY2));
        _partSlots[2] = slot3;
        AddPartStatusPanel(slot3, 2, HandUILocation.Left, PartSize);

        _mainSlot = MakeSlot(MainSize, WeaponAssemblyStationComponent.MainSlotId);
        SlotContainer.AddChild(_mainSlot);
        LayoutContainer.SetPosition(_mainSlot, new Vector2((ContainerWidth - MainSize) / 2f, RowOffsetY2 + PartSize + 12f));

        // #Misfits Add - the weapon's own status panel (name, ammo, attachments)
        // sits to the left of the main slot, matching the right-hand slot UI.
        _mainItemStatus = new ItemStatusPanel
        {
            VerticalAlignment = VAlignment.Center,
            SetWidth = MainPanelWidth,
            MinWidth = MainPanelWidth,
            SetHeight = MainSize,
        };
        _mainItemStatus.SetSide(HandUILocation.Right);
        SlotContainer.AddChild(_mainItemStatus);
        LayoutContainer.SetPosition(_mainItemStatus, new Vector2(_mainSlot.Position.X - MainPanelWidth - PanelGap, _mainSlot.Position.Y));

        _magSlot = MakeSlot(MagSize, WeaponAssemblyStationComponent.Part6SlotId);
        SlotContainer.AddChild(_magSlot);
        LayoutContainer.SetPosition(_magSlot, new Vector2((_mainSlot.Position.X + MainSize) + PanelGap, _mainSlot.Position.Y + (MainSize - MagSize) / 2f));
    }

    private void AddPartStatusPanel(SlotButton slot, int index, HandUILocation side, float size)
    {
        var panel = new ItemStatusPanel
        {
            VerticalAlignment = VAlignment.Center,
            SetWidth = PartPanelWidth,
            MinWidth = PartPanelWidth,
            SetHeight = size,
        };
        panel.SetSide(side);
        SlotContainer.AddChild(panel);

        // A right side panel is drawn on the left of its slot and vice versa.
        var x = side == HandUILocation.Right
            ? slot.Position.X - PartPanelWidth - PanelGap
            : slot.Position.X + size + PanelGap;

        LayoutContainer.SetPosition(panel, new Vector2(x, slot.Position.Y));
        _partItemStatus[index] = panel;
    }

    private SlotButton MakeSlot(float size, string slotId)
    {
        var slot = new SlotButton
        {
            MinSize = new Vector2(size, size),
            SetSize = new Vector2(size, size),
            ButtonTexturePath = "Slots/hand_r",
            SlotName = slotId,
        };

        // #Misfits Add - scale the slot frame and sprite with the control so
        // larger slots (like the 96px main slot) actually centre the weapon.
        slot.SetSlotSize(size);

        slot.Pressed += (args, control) =>
        {
            if (args.Function == EngineKeyFunctions.Use)
                OnSlotPressed?.Invoke(control.SlotName);
        };

        return slot;
    }

    public void UpdateState(WeaponAssemblyBoundUserInterfaceState state)
    {
        BoltButton.Text = Loc.GetString(state.IsBolted
            ? "misfits-weapon-station-unbolt"
            : "misfits-weapon-station-bolt");

        DisassembleButton.Disabled = !state.Powered || state.IsBusy;
        AssembleButton.Disabled = !state.Powered || state.IsBusy;
        BoltButton.Disabled = !state.Powered || state.IsBusy;

        // #Misfits Add - "Восстановить оружие" for a weapon that has no parts to
        // take out, "Восстановить раму" for the frame a modular one is stripped to.
        _repairButtons[0].Text = Loc.GetString(state.BodyRepairIsWeapon
            ? "misfits-weapon-station-repair-weapon"
            : "misfits-weapon-station-repair-frame");

        for (var i = 0; i < _repairButtons.Length; i++)
        {
            var available = state.RepairEnabled != null &&
                            i < state.RepairEnabled.Length &&
                            state.RepairEnabled[i];

            _repairButtons[i].Disabled = !state.Powered || state.IsBusy || !available;
        }

        var entMan = IoCManager.Resolve<IEntityManager>();

        _mainSlot.SetEntity(state.Weapon is { } weapon ? entMan.GetEntity(weapon) : null);
        _magSlot.SetEntity(state.Magazine is { } magazine ? entMan.GetEntity(magazine) : null);

        // #Misfits Add - feed the placed weapon into the status panel.
        _mainItemStatus.Update(state.Weapon is { } statusWeapon ? entMan.GetEntity(statusWeapon) : null);
        _mainItemStatus.SetExtraText(state.Weapon != null && state.WeaponMax > 0f
            ? FormatDurability(state.WeaponCurrent, state.WeaponMax, 0f)
            : null);

        for (var i = 0; i < _partSlots.Length; i++)
        {
            var part = state.Parts != null && i < state.Parts.Length ? state.Parts[i] : null;
            EntityUid? ent = part is { } netEntity ? entMan.GetEntity(netEntity) : null;
            _partSlots[i].SetEntity(ent);
            _partItemStatus[i]?.Update(ent);

            var max = StateAt(state.PartMax, i);

            // #Misfits Add - parts without a durability component (optics, drive)
            // report a zero maximum; show nothing rather than "0/0".
            _partItemStatus[i]?.SetExtraText(ent == null || max <= 0f
                ? null
                : FormatDurability(
                    StateAt(state.PartCurrent, i),
                    max,
                    StateAt(state.PartDeferred, i)));
        }

        UpdateFuel(state.Fuel, state.FuelMax);
    }

    // #Misfits Add - welding fuel gauge in the bottom-right of the window.
    private void UpdateFuel(float fuel, float fuelMax)
    {
        var hasFuel = fuelMax > 0f;
        FuelBar.Value = hasFuel ? Math.Clamp(fuel / fuelMax * 100f, 0f, 100f) : 0f;
        FuelLabel.Text = Loc.GetString("misfits-weapon-station-fuel-label");
        FuelValueLabel.Text = Loc.GetString("misfits-weapon-station-fuel-value",
            ("current", MathF.Round(fuel)),
            ("max", MathF.Round(fuelMax)));

        // Warn with colour as the tank runs dry, mirroring the durability scheme.
        FuelValueLabel.FontColorOverride = !hasFuel || fuel <= 0f
            ? Color.FromHex("#8B0000")
            : fuel / fuelMax <= 0.15f
                ? Color.FromHex("#E53935")
                : fuel / fuelMax <= 0.30f
                    ? Color.FromHex("#FF8C00")
                    : Color.FromHex("#90EE90");
    }

    private static float StateAt(float[]? values, int index)
    {
        return values != null && index < values.Length ? values[index] : 0f;
    }

    // #Misfits Add - exact condition readout for a status panel: remaining and
    // maximum durability, plus the recoverable barrel fouling when there is any.
    // The text is tinted with the same colour the examine readout uses, so the
    // UI and the tooltip agree on what "lightly worn" looks like.
    private static string FormatDurability(float current, float max, float fouled)
    {
        var currentRounded = MathF.Round(current);
        var maxRounded = MathF.Round(max);

        var ratio = max > 0f ? Math.Clamp(current / max, 0f, 1f) : 0f;
        var color = WeaponDurabilityCondition.StateColor(ratio);

        var text = fouled > 0.5f
            ? Loc.GetString("misfits-weapon-station-durability-fouled",
                ("current", currentRounded),
                ("max", maxRounded),
                ("fouled", MathF.Round(fouled)))
            : Loc.GetString("misfits-weapon-station-durability",
                ("current", currentRounded),
                ("max", maxRounded));

        return $"[color={color}]{text}[/color]";
    }
}
