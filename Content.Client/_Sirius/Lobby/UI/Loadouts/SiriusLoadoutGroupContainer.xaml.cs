namespace Content.Client._Sirius.Lobby.UI.Loadouts;

/// <summary>
/// #Sirius Change: Horizon-styled category/group container rendering Sirius loadout items.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SiriusLoadoutGroupContainer : BoxContainer
{
    private readonly List<LoadoutPrototype> _protos;
    private readonly JobPrototype _job;
    private readonly IPrototypeManager _prototype;
    private readonly IEntityManager _entityManager;
    private readonly IConfigurationManager _config;
    private readonly CharacterRequirementsSystem _characterRequirements;
    private readonly JobRequirementsManager _jobRequirements;
    private readonly Content.Client._NC.Sponsor.SponsorManager _sponsorManager;
    private readonly Action<string, bool> _onChanged;
    private readonly Action<string>? _onCustomize;

    private readonly List<(SiriusLoadoutItem Item, LoadoutPrototype Proto, string SearchText, bool JobApplicable)> _items = new();
    private HumanoidCharacterProfile _profile;
    private bool _showUnusable = true;
    private string _searchText = string.Empty;

    public SiriusLoadoutGroupContainer(
        string categoryLabel,
        List<LoadoutPrototype> protos,
        HumanoidCharacterProfile profile,
        JobPrototype job,
        IPrototypeManager prototype,
        IEntityManager entityManager,
        IConfigurationManager config,
        CharacterRequirementsSystem characterRequirements,
        JobRequirementsManager jobRequirements,
        Content.Client._NC.Sponsor.SponsorManager sponsorManager,
        Action<string, bool> onChanged,
        Action<string>? onCustomize = null)
    {
        RobustXamlLoader.Load(this);

        _protos = protos
            .OrderBy(p =>
            {
                var name = Loc.GetString($"loadout-name-{p.ID}");
                return name == $"loadout-name-{p.ID}" ? p.ID : name;
            })
            .ThenBy(p => p.Cost)
            .ToList();

        _profile = profile;
        _job = job;
        _prototype = prototype;
        _entityManager = entityManager;
        _config = config;
        _characterRequirements = characterRequirements;
        _jobRequirements = jobRequirements;
        _sponsorManager = sponsorManager;
        _onChanged = onChanged;
        _onCustomize = onCustomize;

        RestrictionsContainer.DisposeAllChildren();
        RestrictionsContainer.AddChild(new Label
        {
            Text = categoryLabel,
            Margin = new Thickness(5, 0, 5, 5),
        });

        BuildItems();
        RefreshLoadouts(_profile);
    }

    private void BuildItems()
    {
        LoadoutsContainer.DisposeAllChildren();
        _items.Clear();

        foreach (var proto in _protos)
        {
            // #Sirius Change: hide items not permitted for the selected role.
            if (!IsApplicableToJob(proto, _job))
                continue;

            var (valid, reason) = IsValidForJob(proto, _profile);
            var item = new SiriusLoadoutItem(proto, valid, reason, _entityManager);

            // #Sirius Change: per-job loadout preferences.
            var pref = _profile.LoadoutPreferences.FirstOrDefault(p => p.LoadoutName == proto.ID && p.JobName == _job.ID)
                       ?? new LoadoutPreference(proto.ID, jobName: _job.ID);
            item.Select.Pressed = pref.Selected;

            item.Select.OnPressed += args => _onChanged(proto.ID, args.Button.Pressed);
            item.OnCustomizePressed += () => _onCustomize?.Invoke(proto.ID);

            _items.Add((item, proto, item.SearchText, true));
            LoadoutsContainer.AddChild(item);
        }
    }

    public void RefreshLoadouts(HumanoidCharacterProfile profile)
    {
        _profile = profile;

        for (var i = 0; i < _items.Count; i++)
        {
            var (item, proto, search, _) = _items[i];
            // #Sirius Change: per-job loadout preferences.
            var pref = profile.LoadoutPreferences.FirstOrDefault(p => p.LoadoutName == proto.ID && p.JobName == _job.ID)
                       ?? new LoadoutPreference(proto.ID, jobName: _job.ID);
            item.Select.Pressed = pref.Selected;

            var (valid, reason) = IsValidForJob(proto, profile);
            item.SetState(valid, reason);
            _items[i] = (item, proto, search, true);
        }

        ApplyFilter();
    }

    private (bool Valid, FormattedMessage? Reason) IsValidForJob(LoadoutPrototype proto, HumanoidCharacterProfile profile)
    {
        var playTimes = _jobRequirements.GetRawPlayTimeTrackers();
        var whitelisted = _jobRequirements.IsWhitelisted();
        var jobWhitelisted = _jobRequirements.IsJobWhitelisted(_job.ID);

        var valid = _characterRequirements.CheckRequirementsValid(
            proto.Requirements, _job, profile, playTimes, whitelisted, proto,
            _entityManager, _prototype, _config, _sponsorManager, out var reasons, jobWhitelisted: jobWhitelisted);

        FormattedMessage? msg = null;
        if (!valid && reasons.Count > 0)
        {
            var sb = new StringBuilder();
            foreach (var r in reasons)
                sb.AppendLine(r);
            msg = FormattedMessage.FromMarkupPermissive(sb.ToString().TrimEnd());
        }
        return (valid, msg);
    }

    // #Sirius Change: hide loadouts not applicable to this job/faction (role/department restrictions), including logic wrappers.
    private bool IsApplicableToJob(LoadoutPrototype proto, JobPrototype job)
    {
        foreach (var req in proto.Requirements)
        {
            if (GetRoleApplicability(req, job) == RoleApplicability.NotApplicable)
                return false;
        }
        return true;
    }

    private enum RoleApplicability { NotRestricted, Applicable, NotApplicable }

    private RoleApplicability GetRoleApplicability(CharacterRequirement req, JobPrototype job)
    {
        switch (req)
        {
            case CharacterJobRequirement jobReq:
            {
                var match = jobReq.Jobs.Contains(job.ID);
                return (jobReq.Inverted ? !match : match) ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            case CharacterDepartmentRequirement deptReq:
            {
                var inDept = deptReq.Departments.Any(d =>
                    _prototype.TryIndex(d, out DepartmentPrototype? dept) && dept.Roles.Contains(job.ID));
                return (deptReq.Inverted ? !inDept : inDept) ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            case CharacterLogicAndRequirement andReq:
            {
                var anyRestricted = false;
                foreach (var child in andReq.Requirements)
                {
                    var r = GetRoleApplicability(child, job);
                    if (r == RoleApplicability.NotApplicable)
                        return RoleApplicability.NotApplicable;
                    if (r == RoleApplicability.Applicable)
                        anyRestricted = true;
                }
                return anyRestricted ? RoleApplicability.Applicable : RoleApplicability.NotRestricted;
            }
            case CharacterLogicOrRequirement orReq:
            {
                var anyRestricted = false;
                var anyApplicable = false;
                foreach (var child in orReq.Requirements)
                {
                    var r = GetRoleApplicability(child, job);
                    if (r == RoleApplicability.NotRestricted)
                        return RoleApplicability.NotRestricted;
                    if (r == RoleApplicability.Applicable)
                        anyApplicable = true;
                    anyRestricted = true;
                }
                if (!anyRestricted)
                    return RoleApplicability.NotRestricted;
                return anyApplicable ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            case CharacterLogicXorRequirement xorReq:
            {
                var anyRestricted = false;
                var anyApplicable = false;
                foreach (var child in xorReq.Requirements)
                {
                    var r = GetRoleApplicability(child, job);
                    if (r == RoleApplicability.NotRestricted)
                        return RoleApplicability.NotRestricted;
                    if (r == RoleApplicability.Applicable)
                        anyApplicable = true;
                    anyRestricted = true;
                }
                if (!anyRestricted)
                    return RoleApplicability.NotRestricted;
                return anyApplicable ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            default:
                return RoleApplicability.NotRestricted;
        }
    }

    public void FilterLoadouts(string searchText)
    {
        _searchText = searchText ?? string.Empty;
        ApplyFilter();
    }

    private void ApplyFilter()
    {
        var hasSearch = !string.IsNullOrWhiteSpace(_searchText);
        var needle = _searchText.ToLowerInvariant();

        foreach (var (item, _, search, _) in _items)
        {
            var matches = !hasSearch || search.Contains(needle);
            var usableOrShown = _showUnusable || !item.Select.Disabled;
            item.Visible = matches && usableOrShown;
        }
    }

    public bool HasVisibleLoadouts()
    {
        foreach (var (item, _, _, _) in _items)
        {
            if (item.Visible)
                return true;
        }
        return false;
    }
}
