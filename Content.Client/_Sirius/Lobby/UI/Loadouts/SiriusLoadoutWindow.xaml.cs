    public SiriusLoadoutWindow(
        HumanoidCharacterProfile profile,
        JobPrototype job,
        ICommonSession session,
        IPrototypeManager prototype,
        IEntityManager entityManager,
        IConfigurationManager config,
        CharacterRequirementsSystem characterRequirements,
        JobRequirementsManager jobRequirements,
        Content.Client._NC.Sponsor.SponsorManager sponsorManager,
        Dictionary<string, EntityUid> dummyEntities,
        Func<HumanoidCharacterProfile, HumanoidCharacterProfile> applyProfile,
        Action reloadPreview)
    {
        RobustXamlLoader.Load(this);

        _profile = profile;
        _job = job;
        _prototype = prototype;
        _entityManager = entityManager;
        _config = config;
        _characterRequirements = characterRequirements;
        _jobRequirements = jobRequirements;
        _sponsorManager = sponsorManager;
        _applyProfile = applyProfile;
        _reloadPreview = reloadPreview;

        Title = Loc.GetString("loadout-window-title-loadout", ("job", job.LocalizedName));

        SearchBar.OnTextChanged += args =>
        {
            _searchText = args.Text;
            ApplySearchFilter();
        };

        ResetLoadoutButton.OnPressed += _ => ResetLoadout();

        BuildTabs();
        Refresh();
    }

    public void SetProfile(HumanoidCharacterProfile profile)
    {
        _profile = profile;
        Refresh();
    }

    private bool _tabsBuilt;

    private void BuildTabs()
    {
        if (_tabsBuilt)
            return;

        try
        {
            // #Sirius Fix: never DisposeAllChildren() on VerticalTabContainer - it destroys internal tab structure.
            _groups.Clear();

            var visible = GetVisibleLoadoutsForJob();
            var byCategory = visible
                .GroupBy(l => l.Category.Id)
                .ToDictionary(g => g.Key, g => g.ToList());

            var roots = _prototype.EnumeratePrototypes<LoadoutCategoryPrototype>()
                .Where(c => c.Root)
                .OrderBy(c => Loc.GetString($"loadout-category-{c.ID}"))
                .ToList();

            var knownCats = new HashSet<string>();
            foreach (var root in roots)
                CollectCategoryIds(root, knownCats);

            var addedAny = false;

            foreach (var root in roots)
            {
                // #Sirius Change: hide Patreon category from loadout UI.
                if (root.ID == "Patreon")
                    continue;

                if (!TryCreateCategoryTab(root, byCategory, out var control, out var label, out var groupList))
                    continue;

                foreach (var g in groupList)
                    _groups.Add(g);

                LoadoutGroupsContainer.AddTab(control, label);
                addedAny = true;
            }

            // Leftovers / items whose category isn't under any root tree.
            var uncategorized = visible.Where(l => !knownCats.Contains(l.Category)).ToList();
            if (uncategorized.Count > 0)
            {
                var tabName = Loc.GetString("loadout-category-Uncategorized");
                var container = CreateLoadoutGroup(tabName, uncategorized);
                _groups.Add(container);
                LoadoutGroupsContainer.AddTab(container, tabName);
                addedAny = true;
            }

            // Fallback: if mapping failed for some reason, still show all Sirius loadouts.
            if (!addedAny && visible.Count > 0)
            {
                var tabName = Loc.GetString("humanoid-profile-editor-loadouts");
                var container = CreateLoadoutGroup(tabName, visible);
                _groups.Add(container);
                LoadoutGroupsContainer.AddTab(container, tabName);
                addedAny = true;
            }

            // Horizon-like access to tab buttons for search-disabling tabs.
            _tabButtonContainer = null;
            try
            {
                if (_groups.Count > 0 && LoadoutGroupsContainer.ChildCount > 0)
                    _tabButtonContainer = LoadoutGroupsContainer.GetChild(0).GetChild(0).GetChild(0);
            }
            catch
            {
                _tabButtonContainer = null;
            }

            if (!addedAny)
            {
                LoadoutGroupsContainer.AddTab(
                    new Label { Text = Loc.GetString("humanoid-profile-editor-loadouts-no-loadouts"), Margin = new Thickness(10) },
                    Loc.GetString("humanoid-profile-editor-loadouts"));
            }

            _tabsBuilt = true;
        }
        catch (Exception e)
        {
            // #Sirius Fix: show visible error instead of leaving window silently empty.
            try
            {
                LoadoutGroupsContainer.AddTab(
                    new Label { Text = $"[Sirius] Loadout UI error: {e.Message}", Margin = new Thickness(10) },
                    "Error");
            }
            catch { }
            _tabsBuilt = true;
        }
    }

    private SiriusLoadoutGroupContainer CreateLoadoutGroup(string label, List<LoadoutPrototype> protos)
    {
        return new SiriusLoadoutGroupContainer(
            label,
            protos,
            _profile,
            _job,
            _prototype,
            _entityManager,
            _config,
            _characterRequirements,
            _jobRequirements,
            _sponsorManager,
            OnPreferenceChanged,
            OpenCustomizeDialog);
    }

    private bool TryCreateCategoryTab(
        LoadoutCategoryPrototype root,
        Dictionary<string, List<LoadoutPrototype>> byCategory,
        out Control control,
        out string label,
        out List<SiriusLoadoutGroupContainer> groups)
    {
        control = default!;
        label = Loc.GetString($"loadout-category-{root.ID}");
        groups = new List<SiriusLoadoutGroupContainer>();

        // Gather direct items and per-subcategory items.
        byCategory.TryGetValue(root.ID, out var direct);
        direct ??= new List<LoadoutPrototype>();

        var subWithItems = new List<(LoadoutCategoryPrototype Cat, List<LoadoutPrototype> Items)>();
        foreach (var subId in root.SubCategories)
        {
            if (!_prototype.TryIndex(subId, out var sub))
                continue;
            var items = CollectCategoryLoadouts(sub, byCategory);
            if (items.Count > 0)
                subWithItems.Add((sub, items));
        }

        var total = direct.Count + subWithItems.Sum(s => s.Items.Count);
        if (total == 0)
            return false;

        // #Sirius Change: if root has subcategories with items, create nested VerticalTabContainer (second tab row/column).
        if (subWithItems.Count > 0)
        {
            var nested = new VerticalTabContainer { VerticalExpand = true, HorizontalExpand = true };

            if (direct.Count > 0)
            {
                var allLabel = label;
                var c = CreateLoadoutGroup(allLabel, direct);
                groups.Add(c);
                nested.AddTab(c, allLabel);
            }

            foreach (var (sub, items) in subWithItems.OrderBy(s => Loc.GetString($"loadout-category-{s.Cat.ID}")))
            {
                var subLabel = Loc.GetString($"loadout-category-{sub.ID}");
                var c = CreateLoadoutGroup(subLabel, items);
                groups.Add(c);
                nested.AddTab(c, subLabel);
            }

            control = nested;
            return true;
        }

        var container = CreateLoadoutGroup(label, direct);
        groups.Add(container);
        control = container;
        return true;
    }

    private void CollectCategoryIds(LoadoutCategoryPrototype cat, HashSet<string> ids)
    {
        ids.Add(cat.ID);
        foreach (var subId in cat.SubCategories)
        {
            if (_prototype.TryIndex(subId, out var sub))
                CollectCategoryIds(sub, ids);
        }
    }

    private List<LoadoutPrototype> CollectCategoryLoadouts(LoadoutCategoryPrototype cat, Dictionary<string, List<LoadoutPrototype>> byCategory)
    {
        var result = new List<LoadoutPrototype>();
        if (byCategory.TryGetValue(cat.ID, out var direct))
            result.AddRange(direct);

        foreach (var subId in cat.SubCategories)
        {
            if (_prototype.TryIndex(subId, out var sub))
                result.AddRange(CollectCategoryLoadouts(sub, byCategory));
        }

        return result;
    }

    private List<LoadoutPrototype> GetVisibleLoadoutsForJob()
    {
        // #Sirius Change: show only items permitted for the selected role (hide role-inapplicable items).
        return _prototype.EnumeratePrototypes<LoadoutPrototype>()
            .Where(p => IsApplicableToJob(p, _job))
            .ToList();
    }

    // #Sirius Change: hide loadouts not applicable to this job/faction (role/department restrictions), including logic wrappers.
    private bool IsApplicableToJob(LoadoutPrototype proto, JobPrototype job)
    {
        foreach (var req in proto.Requirements)
        {
            if (GetRoleApplicability(req, job) == RoleApplicability.NotApplicable)
                return false;
        }
        return true;
    }

    private enum RoleApplicability { NotRestricted, Applicable, NotApplicable }

    private RoleApplicability GetRoleApplicability(CharacterRequirement req, JobPrototype job)
    {
        switch (req)
        {
            case CharacterJobRequirement jobReq:
            {
                var match = jobReq.Jobs.Contains(job.ID);
                return (jobReq.Inverted ? !match : match) ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            case CharacterDepartmentRequirement deptReq:
            {
                var inDept = deptReq.Departments.Any(d =>
                    _prototype.TryIndex(d, out DepartmentPrototype? dept) && dept.Roles.Contains(job.ID));
                return (deptReq.Inverted ? !inDept : inDept) ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            case CharacterLogicAndRequirement andReq:
            {
                var anyRestricted = false;
                foreach (var child in andReq.Requirements)
                {
                    var r = GetRoleApplicability(child, job);
                    if (r == RoleApplicability.NotApplicable)
                        return RoleApplicability.NotApplicable;
                    if (r == RoleApplicability.Applicable)
                        anyRestricted = true;
                }
                return anyRestricted ? RoleApplicability.Applicable : RoleApplicability.NotRestricted;
            }
            case CharacterLogicOrRequirement orReq:
            {
                var anyRestricted = false;
                var anyApplicable = false;
                foreach (var child in orReq.Requirements)
                {
                    var r = GetRoleApplicability(child, job);
                    if (r == RoleApplicability.NotRestricted)
                        return RoleApplicability.NotRestricted;
                    if (r == RoleApplicability.Applicable)
                        anyApplicable = true;
                    anyRestricted = true;
                }
                if (!anyRestricted)
                    return RoleApplicability.NotRestricted;
                return anyApplicable ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            case CharacterLogicXorRequirement xorReq:
            {
                var anyRestricted = false;
                var anyApplicable = false;
                foreach (var child in xorReq.Requirements)
                {
                    var r = GetRoleApplicability(child, job);
                    if (r == RoleApplicability.NotRestricted)
                        return RoleApplicability.NotRestricted;
                    if (r == RoleApplicability.Applicable)
                        anyApplicable = true;
                    anyRestricted = true;
                }
                if (!anyRestricted)
                    return RoleApplicability.NotRestricted;
                return anyApplicable ? RoleApplicability.Applicable : RoleApplicability.NotApplicable;
            }
            default:
                return RoleApplicability.NotRestricted;
        }
    }

    private void OnPreferenceChanged(string loadoutId, bool selected)
    {
        // #Sirius Change: per-job loadout preferences.
        var pref = _profile.LoadoutPreferences.FirstOrDefault(p => p.LoadoutName == loadoutId && p.JobName == _job.ID)
                   ?? new LoadoutPreference(loadoutId, jobName: _job.ID);

        // enforce points budget
        if (selected && !pref.Selected)
        {
            var budget = GetPointBudget();
            var used = GetUsedPoints(except: loadoutId);
            if (_prototype.TryIndex<LoadoutPrototype>(loadoutId, out var lp) && used + lp.Cost > budget)
            {
                Refresh();
                return;
            }
        }

        _profile = _profile.WithLoadoutPreference(
            loadoutId,
            selected,
            pref.CustomName,
            pref.CustomDescription,
            pref.CustomColorTint,
            pref.CustomHeirloom,
            _job.ID);
        _profile = _applyProfile(_profile);
        _reloadPreview();
        Refresh();
    }

    public void Refresh()
    {
        foreach (var group in _groups)
            group.RefreshLoadouts(_profile);

        UpdatePoints();
        ApplySearchFilter();
    }

    private void UpdatePoints()
    {
        var budget = GetPointBudget();
        var used = GetUsedPoints();
        // #Sirius Change: show remaining/available points (12/12 = all available, 0/12 = all spent).
        var remaining = Math.Max(0, budget - used);

        Cost.Text = Loc.GetString("humanoid-profile-editor-loadouts-points-label", ("points", remaining), ("max", budget));
        Balance.Text = string.Empty;
        Balance.Visible = false;
        PointsBar.MaxValue = Math.Max(1, budget);
        PointsBar.Value = Math.Clamp(remaining, 0, budget);

        // #Sirius Change: reset button replaces "remove unusable" - clears all selected loadouts for this job.
        var selectedCount = _profile.LoadoutPreferences.Count(p => p.JobName == _job.ID && p.Selected);
        ResetLoadoutButton.Disabled = selectedCount == 0;
    }

    private int GetPointBudget()
    {
        // #Sirius Change: align with shared/server budget calculation.
        var basePoints = _config.GetCVar(CCVars.GameLoadoutsPoints);
        var charisma = Content.Shared._Misfits.Special.SpecialProfile.EnsureValid(_profile.Special).Charisma;
        basePoints += Content.Shared._Misfits.Special.SharedSpecialSystem.GetCharismaLoadoutPointModifier(charisma);
        return Math.Max(0, basePoints);
    }

    private int GetUsedPoints(string? except = null)
    {
        // #Sirius Change: count points for this job's loadout set only.
        var total = 0;
        foreach (var pref in _profile.LoadoutPreferences)
        {
            if (pref.JobName != _job.ID)
                continue;
            if (!pref.Selected)
                continue;
            if (except != null && pref.LoadoutName == except)
                continue;
            if (_prototype.TryIndex<LoadoutPrototype>(pref.LoadoutName, out var lp))
                total += lp.Cost;
        }
        return total;
    }

    // #Sirius Change: reset all selected loadouts for this job.
    private void ResetLoadout()
    {
        var changed = false;
        foreach (var pref in _profile.LoadoutPreferences.ToList())
        {
            if (pref.JobName != _job.ID || !pref.Selected)
                continue;

            _profile = _profile.WithLoadoutPreference(
                pref.LoadoutName, false,
                pref.CustomName, pref.CustomDescription, pref.CustomColorTint, pref.CustomHeirloom,
                _job.ID);
            changed = true;
        }

        if (!changed)
            return;

        _profile = _applyProfile(_profile);
        _reloadPreview();
        Refresh();
    }

    private void ApplySearchFilter()
    {
        try
        {
            var hasSearch = !string.IsNullOrWhiteSpace(_searchText);
            var canSyncTabs = _tabButtonContainer != null && _tabButtonContainer.ChildCount == _groups.Count;

            for (var i = 0; i < _groups.Count; i++)
            {
                _groups[i].FilterLoadouts(_searchText);
                if (canSyncTabs && i < _tabButtonContainer!.ChildCount && _tabButtonContainer.GetChild(i) is BaseButton button)
                    button.Disabled = hasSearch && !_groups[i].HasVisibleLoadouts();
            }
        }
        catch
        {
            // #Sirius Fix: ignore tab sync issues, keep search functional.
        }
    }

    // #Sirius Add: customization dialog for Sirius loadout preferences.
    private void OpenCustomizeDialog(string loadoutId)
    {
        if (!_prototype.TryIndex<LoadoutPrototype>(loadoutId, out var proto))
            return;

        var pref = _profile.LoadoutPreferences.FirstOrDefault(p => p.LoadoutName == loadoutId && p.JobName == _job.ID)
                   ?? new LoadoutPreference(loadoutId, jobName: _job.ID);

        var canName = proto.CustomName;
        var canDesc = proto.CustomDescription;
        var canColor = proto.CustomColorTint;
        var canHeirloom = proto.CanBeHeirloom;
        if (!canName && !canDesc && !canColor && !canHeirloom)
            return;

        var window = new DefaultWindow
        {
            Title = Loc.GetString("humanoid-profile-editor-loadouts-customize"),
            MinSize = new Vector2(420, 300),
        };

        var root = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(8) };

        LineEdit? nameEdit = null;
        if (canName)
        {
            root.AddChild(new Label { Text = Loc.GetString("humanoid-profile-editor-loadouts-customize-name") });
            nameEdit = new LineEdit { Text = pref.CustomName ?? string.Empty, HorizontalExpand = true };
            root.AddChild(nameEdit);
        }

        TextEdit? descEdit = null;
        if (canDesc)
        {
            root.AddChild(new Label { Text = Loc.GetString("humanoid-profile-editor-loadouts-customize-description"), Margin = new Thickness(0, 6, 0, 0) });
            descEdit = new TextEdit { MinSize = new Vector2(0, 80), HorizontalExpand = true };
            if (!string.IsNullOrEmpty(pref.CustomDescription))
                descEdit.TextRope = new Rope.Leaf(pref.CustomDescription);
            root.AddChild(descEdit);
        }

        ColorSelectorSliders? colorSelector = null;
        CheckBox? enableColor = null;
        if (canColor)
        {
            enableColor = new CheckBox
            {
                Text = Loc.GetString("humanoid-profile-editor-loadouts-customize-color"),
                Pressed = pref.CustomColorTint != null,
                Margin = new Thickness(0, 6, 0, 0)
            };
            root.AddChild(enableColor);
            colorSelector = new ColorSelectorSliders { Visible = pref.CustomColorTint != null };
            if (!string.IsNullOrEmpty(pref.CustomColorTint) && Color.TryFromHex(pref.CustomColorTint, out var c))
                colorSelector.Color = c;
            else
                colorSelector.Color = Color.White;
            enableColor.OnToggled += args => colorSelector.Visible = args.Pressed;
            root.AddChild(colorSelector);
        }

        CheckBox? heirloom = null;
        if (canHeirloom)
        {
            heirloom = new CheckBox
            {
                Text = Loc.GetString("humanoid-profile-editor-loadouts-customize-heirloom"),
                Pressed = pref.CustomHeirloom ?? false,
                Margin = new Thickness(0, 6, 0, 0)
            };
            root.AddChild(heirloom);
        }

        var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalAlignment = HAlignment.Right, Margin = new Thickness(0, 8, 0, 0) };
        var saveBtn = new Button { Text = Loc.GetString("humanoid-profile-editor-loadouts-customize-save") };
        var closeBtn = new Button { Text = Loc.GetString("window-close") };
        closeBtn.OnPressed += _ => window.Close();
        saveBtn.OnPressed += _ =>
        {
            var current = _profile.LoadoutPreferences.FirstOrDefault(p => p.LoadoutName == loadoutId && p.JobName == _job.ID)
                          ?? new LoadoutPreference(loadoutId, jobName: _job.ID);

            var newName = canName ? (string.IsNullOrWhiteSpace(nameEdit?.Text) ? null : nameEdit!.Text) : current.CustomName;
            var newDesc = canDesc ? (string.IsNullOrWhiteSpace(descEdit != null ? Rope.Collapse(descEdit.TextRope) : null) ? null : Rope.Collapse(descEdit!.TextRope)) : current.CustomDescription;
            string? newColor = current.CustomColorTint;
            if (canColor)
                newColor = (enableColor?.Pressed ?? false) ? (colorSelector?.Color.ToHex() ?? current.CustomColorTint) : null;
            bool? newHeirloom = current.CustomHeirloom;
            if (canHeirloom)
                newHeirloom = heirloom?.Pressed ?? false;

            _profile = _profile.WithLoadoutPreference(loadoutId, current.Selected, newName, newDesc, newColor, newHeirloom, _job.ID);
            _profile = _applyProfile(_profile);
            _reloadPreview();
            Refresh();
            window.Close();
        };
        buttons.AddChild(closeBtn);
        buttons.AddChild(new Control { MinSize = new Vector2(6, 0) });
        buttons.AddChild(saveBtn);
        root.AddChild(buttons);

        window.Contents.AddChild(root);
        window.OpenCentered();
    }
