using System.Text;
using Content.Client.Stylesheets;
using Content.Shared.Clothing.Loadouts.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Sirius.Lobby.UI.Loadouts;

/// <summary>
/// #Sirius Change: Horizon-styled loadout item row adapted to Sirius LoadoutPrototype data/points.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SiriusLoadoutItem : BoxContainer
{
    private readonly IEntityManager _entManager;
    private EntityUid? _entity;
    private string _description = string.Empty;

    public Button Select => SelectButton;
    public event Action? OnCustomizePressed;

    public string? Text
    {
        get => SelectButton.Text;
        set => SelectButton.Text = value;
    }

    public string SearchText { get; private set; } = string.Empty;
    public string ProtoId { get; }

    public SiriusLoadoutItem(
        LoadoutPrototype proto,
        bool enabled,
        FormattedMessage? reason,
        IEntityManager entManager)
    {
        RobustXamlLoader.Load(this);
        _entManager = entManager;
        ProtoId = proto.ID;

        Price.Text = proto.Cost.ToString();

        // #Sirius Add: customization support for Sirius loadout prefs.
        var canCustomize = proto.CustomName || proto.CustomDescription || proto.CustomColorTint || proto.CanBeHeirloom;
        CustomizeButton.Visible = canCustomize;
        CustomizeButton.OnPressed += _ => OnCustomizePressed?.Invoke();

        EntityUid? preview = null;
        if (proto.Items.Count > 0)
        {
            try
            {
                preview = _entManager.SpawnEntity(proto.Items[0], MapCoordinates.Nullspace);
                _entity = preview;
                Sprite.SetEntity(preview);
            }
            catch
            {
                // #Sirius Fix: keep row usable even if preview entity fails to spawn.
            }
        }

        var nameKey = $"loadout-name-{proto.ID}";
        var name = Loc.GetString(nameKey);
        if (name == nameKey)
        {
            if (preview != null && _entManager.TryGetComponent(preview.Value, out MetaDataComponent? meta))
                name = meta.EntityName;
            else
                name = proto.ID;
        }

        var descKey = $"loadout-description-{proto.ID}";
        var desc = Loc.GetString(descKey);
        if (desc == descKey)
        {
            if (preview != null && _entManager.TryGetComponent(preview.Value, out MetaDataComponent? meta2))
                desc = meta2.EntityDescription;
            else
                desc = string.Empty;
        }

        _description = desc ?? string.Empty;
        Text = name;
        SearchText = $"{name} {proto.ID}".ToLowerInvariant();

        SetState(enabled, reason);
    }

    public void SetState(bool enabled, FormattedMessage? reason)
    {
        SelectButton.Disabled = !enabled;

        // Horizon-like: disabled items still visible; reason in tooltip.
        if (!enabled)
            SelectButton.AddStyleClass(StyleBase.ButtonCaution);
        else
            SelectButton.RemoveStyleClass(StyleBase.ButtonCaution);

        var tip = new StringBuilder();
        if (!string.IsNullOrWhiteSpace(_description))
            tip.Append(_description);
        if (reason != null)
        {
            var reasonText = reason.ToMarkup().Trim();
            if (!string.IsNullOrWhiteSpace(reasonText))
            {
                if (tip.Length > 0)
                    tip.Append("\n");
                tip.Append(reasonText);
            }
        }

        if (tip.Length > 0)
        {
            var formatted = FormattedMessage.FromMarkupPermissive(tip.ToString());
            var spriteTooltip = new Tooltip();
            spriteTooltip.SetMessage(formatted);
            Sprite.TooltipSupplier = _ => spriteTooltip;

            var buttonTooltip = new Tooltip();
            buttonTooltip.SetMessage(formatted);
            SelectButton.TooltipSupplier = _ => buttonTooltip;
        }
        else
        {
            Sprite.TooltipSupplier = null;
            SelectButton.TooltipSupplier = null;
        }
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (!disposing)
            return;
        if (_entity != null)
        {
            _entManager.QueueDeleteEntity(_entity.Value);
            _entity = null;
        }
    }
}
