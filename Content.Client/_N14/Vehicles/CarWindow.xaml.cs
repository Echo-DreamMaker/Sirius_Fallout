// #Sirius Add - car console window (adapted from the Vertibird flight console).
using System;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._N14.Vehicles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._N14.Vehicles;

[GenerateTypedNameReferences]
public sealed partial class CarWindow : FancyWindow
{
    public event Action<int>? OnSeatSelected;
    public event Action? OnLoadCargo;
    public event Action<NetEntity>? OnUnloadCargo;

    public CarWindow()
    {
        RobustXamlLoader.Load(this);

        LoadCargoButton.OnPressed += _ => OnLoadCargo?.Invoke();
    }

    public void SetState(CarBoundUiState state)
    {
        Title = state.Title;

        var status = Loc.GetString(state.EngineRunning ? "car-state-running" : "car-state-off");
        StatusLabel.Text = Loc.GetString("car-window-status", ("state", status));

        var occupied = state.Seats.Count(seat => seat.OccupantName != null);
        OccupancyLabel.Text = Loc.GetString("car-window-occupancy",
            ("occupied", occupied),
            ("capacity", state.Seats.Length));

        HullBar.MaxValue = Math.Max(state.MaxIntegrity, 1f);
        HullBar.Value = Math.Clamp(state.Integrity, 0f, HullBar.MaxValue);
        HullText.Text = Loc.GetString("car-window-hull-value",
            ("integrity", MathF.Round(state.Integrity)),
            ("max", MathF.Round(state.MaxIntegrity)));

        PilotList.RemoveAllChildren();
        PassengerList.RemoveAllChildren();

        foreach (var seat in state.Seats)
        {
            var list = seat.Index == 0 ? PilotList : PassengerList;
            list.AddChild(BuildSeatRow(seat));
        }

        CargoLabel.Text = Loc.GetString("car-window-cargo-count",
            ("stored", state.Cargo.Length),
            ("capacity", state.CargoCapacity));

        CargoList.RemoveAllChildren();
        if (state.Cargo.Length == 0)
        {
            CargoList.AddChild(new Label
            {
                Text = Loc.GetString("car-cargo-empty"),
                HorizontalExpand = true,
            });
        }
        else
        {
            foreach (var crate in state.Cargo)
                CargoList.AddChild(BuildCargoRow(crate));
        }

        LoadCargoButton.Disabled = state.Cargo.Length >= state.CargoCapacity;
    }

    private Control BuildCargoRow(CarCargoUiState crate)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 6),
        };

        row.AddChild(new Label
        {
            Text = crate.Name,
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
        });

        var button = new Button
        {
            Text = Loc.GetString("car-cargo-unload"),
            MinWidth = 84,
        };
        button.OnPressed += _ => OnUnloadCargo?.Invoke(crate.Crate);

        row.AddChild(button);
        return row;
    }

    private Control BuildSeatRow(CarSeatUiState seat)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 6),
        };

        row.AddChild(new Label
        {
            Text = seat.Name,
            MinWidth = 132,
            VerticalAlignment = VAlignment.Center,
        });

        row.AddChild(new Label
        {
            Text = seat.OccupantName ?? Loc.GetString("car-seat-empty"),
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
        });

        var button = new Button
        {
            Text = seat.OccupantName == null
                ? Loc.GetString("car-seat-board")
                : Loc.GetString("car-seat-occupied"),
            Disabled = seat.OccupantName != null,
            MinWidth = 84,
        };
        button.OnPressed += _ => OnSeatSelected?.Invoke(seat.Index);

        row.AddChild(button);
        return row;
    }
}
